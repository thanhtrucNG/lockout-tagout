// Writes docs/translation-review-loto.md: every EN → VI pair on the site, for review by a Vietnamese speaker (template §8.2).
// Usage: node scripts/make-translation-review.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const locale = fs.readFileSync(path.join(root, 'src/lib/locale.js'), 'utf8');
const start = locale.indexOf('  // Lockout tagout product copy.');
const end = locale.indexOf("  'Skip to order'");
const block = new Function(`return {${locale.slice(start, end)}}`)();
const config = JSON.parse(fs.readFileSync(path.join(root, 'src/data/configurator.json'), 'utf8'));
const labels = (await import(path.join(root, 'src/data/labels-vi.js').replace(/\\/g, '/').replace(/^([A-Za-z]):/, 'file:///$1:'))).default;
const row = (area, key, en, vi) => `| ${area} | ${key} | ${String(en).replace(/\|/g, '\\|')} | ${String(vi).replace(/\|/g, '\\|')} | |`;
const lines = [
  '# Translation review: Lockout Tagout landing page',
  '',
  'Generated by `scripts/make-translation-review.mjs`. **Needs review by a Vietnamese speaker** before launch (template §8.1, §8.2). Fill the Issue column; fix in `src/lib/locale.js` (page copy), `scripts/loto/*.mjs` (product names and labels), then re-run the merge and build scripts.',
  '',
  'Terms used on purpose: *khóa an toàn lockout* (lockout padlock), *móc khóa* (hasp), *aptomat* (circuit breaker), *khóa van* (valve lockout), *thẻ* (tag), *trạm* (station), *cùng chìa / khác chìa* (keyed alike / different). Please confirm they match what Handyman sales use.',
  '',
  '## Page copy', '', '| Area | Key | EN | VI | Issue |', '|---|---|---|---|---|',
  ...Object.entries(block).map(([en, vi]) => row('Page', 'locale.js', en, vi)),
  '', '## Product types (step "Choose a product")', '', '| Area | Key | EN | VI | Issue |', '|---|---|---|---|---|',
  ...config.concepts.map(concept => row('Product type', concept.id.split(':')[1], concept.label_en, concept.label_vi)),
  '', '## Size, design and pack labels (step 3 to 5, order rows)', '', '| Area | Key | EN | VI | Issue |', '|---|---|---|---|---|',
  ...Object.entries(labels).map(([en, vi]) => row('Label', 'labels-vi.js', en, vi)),
  '',
];
fs.writeFileSync(path.join(root, 'docs/translation-review-loto.md'), lines.join('\n'));
console.log(`docs/translation-review-loto.md: ${Object.keys(block).length} page strings, ${config.concepts.length} product types, ${Object.keys(labels).length} labels`);
